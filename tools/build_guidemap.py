#!/usr/bin/env python3
"""Builds GuideMap.lua: the same RestedXP guide in every client language.

RestedXP ships the WoW Forever guides once per language (English in Guides/,
the others in lang/Guides-<locale>/). A German client only loads the German
copies, and their group and guide names differ from the English ones. Each
translation has the same files with the guides in the same order, so
"file + position in the file" names a guide the same way in every language.

Usage (rerun after RestedXP updates its guides):
    git clone --depth 1 https://github.com/RestedXP/RXPGuides.git /tmp/RXPGuides
    python3 tools/build_guidemap.py /tmp/RXPGuides > GuideMap.lua
"""
import os
import re
import sys

LISTS = {"enUS": "Guides/GuideList-forever.xml"}
QUEST_RE = re.compile(r"^\s*\.(?:accept|turnin|complete)\s+(\d+)", re.M)


def affix(name):
    # same as RestedXP: "1-6 Durotar" -> "01-06 Durotar"
    def rep(m):
        smin, smax = m.group(1), m.group(2)
        if len(smax) == 1:
            smax = "0" + smax
        return "0" + smin + "-" + smax
    return re.sub(r"^(\d)-(\d\d?)", rep, name, count=1)


def guides_in(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    out = []
    for block in re.split(r"RegisterGuide\(", text)[1:]:
        head = re.match(r'\s*"([^"]+)"\s*,', block)   # RegisterGuide("Group", [[...
        name = re.search(r"^#name\s+(.+?)\s*$", block, re.M)
        group = re.search(r"^#group\s+(.+?)\s*$", block, re.M)
        if not name:
            continue
        g = group.group(1) if group else (head.group(1) if head else None)
        if not g:
            continue
        # "#group X << Alliance": RestedXP strips the condition
        g = re.sub(r"\s*<<.*$", "", g)
        n = re.sub(r"\s*<<.*$", "", name.group(1))
        out.append({"group": g, "name": affix(n), "quests": QUEST_RE.findall(block)})
    return out


def files_in(root, xml_rel):
    xml = os.path.join(root, xml_rel)
    base = os.path.dirname(xml)
    files = []
    for f in re.findall(r'<Script\s+file="([^"]+)"', open(xml, encoding="utf-8").read()):
        f = f.replace("\\", "/")
        if f.startswith("Guides/"):
            full = os.path.join(root, f)
        else:
            full = os.path.join(base, f)
        rel = re.sub(r"^.*?(?:Guides/|Guides-[a-zA-Z]{4}/)", "", f)
        if os.path.basename(f).lower() == "import.lua" or not os.path.exists(full):
            continue
        files.append((rel, full))
    return files


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(root):
    for d in sorted(os.listdir(os.path.join(root, "lang"))):
        m = re.match(r"Guides-([a-zA-Z]{4})$", d)
        if m and os.path.exists(os.path.join(root, "lang", d, "GuideList-forever.xml")):
            LISTS[m.group(1)] = "lang/%s/GuideList-forever.xml" % d

    per_lang = {}
    for loc, xml in LISTS.items():
        per_lang[loc] = {rel: guides_in(full) for rel, full in files_in(root, xml)}

    ids, warnings = [], []
    for rel, en_guides in per_lang["enUS"].items():
        for i, en in enumerate(en_guides, 1):
            gid = "%s#%d" % (rel, i)
            names = {"enUS": (en["group"], en["name"])}
            for loc, files in per_lang.items():
                if loc == "enUS" or rel not in files:
                    continue
                tr = files[rel]
                if len(tr) != len(en_guides):
                    warnings.append("%s %s: %d guides, enUS %d" % (loc, rel, len(tr), len(en_guides)))
                    continue
                if tr[i - 1]["quests"] != en["quests"]:
                    # translations can lag behind a guide update; same guide if most quests match
                    a, b = set(tr[i - 1]["quests"]), set(en["quests"])
                    overlap = len(a & b) / max(1, len(a | b))
                    if overlap < 0.5:
                        warnings.append("%s %s: quests differ (%.0f%%), skipped" % (loc, gid, overlap * 100))
                        continue
                    warnings.append("%s %s: quests differ a bit (%.0f%% the same), kept" % (loc, gid, overlap * 100))
                if (tr[i - 1]["group"], tr[i - 1]["name"]) != names["enUS"]:
                    names[loc] = (tr[i - 1]["group"], tr[i - 1]["name"])
            ids.append((gid, names))

    print("-- Syncline: the same RestedXP guide in every client language.")
    print("-- Generated by tools/build_guidemap.py, don't edit by hand.")
    print("-- [id] = { enUS = { group, name }, <locale> = { group, name } when it differs }")
    print("local ADDON, ns = ...")
    print("ns.GuideMap = {")
    for gid, names in ids:
        parts = ["%s = { %s, %s }" % (loc, lua_str(g), lua_str(n)) for loc, (g, n) in sorted(names.items())]
        print("    [%s] = { %s }," % (lua_str(gid), ", ".join(parts)))
    print("}")
    for w in warnings:
        sys.stderr.write("warning: " + w + "\n")
    sys.stderr.write("%d guides\n" % len(ids))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
